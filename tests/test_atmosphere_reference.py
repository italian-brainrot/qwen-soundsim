"""The always-running cross-check of the atmospheric absorption model.

AUDIT.md pass 1, finding F6: the check the README quotes was
``pytest.importorskip("acoustic_toolbox")``, so on every machine without that
package the model's headline verification silently skipped -- and air absorption
drives every long outdoor scene.  This test runs everywhere: the reference values
are vendored as a plain table (``tests/data/atmosphere_alpha_reference.csv``,
generated by ``tools/make_atmosphere_reference.py`` from a different published
implementation of ISO 9613-1:1993 Annex A, BSD 3-clause, attributed in the file).
"""
from __future__ import annotations

import csv
import os

import numpy as np
import pytest

from soundsim.acoustics import atmosphere

TABLE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data",
                     "atmosphere_alpha_reference.csv")

#: The reference table rounds nothing, but the two implementations differ in
#: their formulation of the humidity dependence; the measured worst case over the
#: grid is 1.5 % (hot-and-humid, 63 Hz).  Anything above 3 % is a real
#: disagreement about the physics, not a rounding argument.
TOLERANCE = 0.03


FIELDS = ("temp_c", "rh_pct", "freq_hz", "alpha_db_per_m")


def _rows():
    with open(TABLE) as fh:
        # every line of this fixture, including the column names, is a comment:
        # the table is data, and it is read by field position, not by header
        lines = [ln for ln in fh if not ln.startswith("#") and ln.strip()]
    for rec in csv.DictReader(lines, fieldnames=FIELDS):
        yield (float(rec["temp_c"]), float(rec["rh_pct"]), float(rec["freq_hz"]),
               float(rec["alpha_db_per_m"]))


def test_vendored_reference_table_exists_and_covers_the_advertised_range():
    """The README promises the check over -20...+50 C, 10-90 % RH; the fixture
    that makes that promise keep running has to actually span it."""
    data = list(_rows())
    assert len(data) > 100
    temps = {t for t, _, _, _ in data}
    rhs = {r for _, r, _, _ in data}
    freqs = {f for _, _, f, _ in data}
    assert min(temps) <= -20.0 and max(temps) >= 50.0
    assert min(rhs) <= 10.0 and max(rhs) >= 90.0
    assert min(freqs) <= 125.0 and max(freqs) >= 4000.0
    assert all(a > 0.0 for *_, a in data)


@pytest.mark.parametrize("temp_c,rh_pct", sorted({(t, r) for t, r, _, _ in _rows()}))
def test_atmosphere_matches_the_vendored_reference(temp_c, rh_pct):
    """Every tabulated value, one assertion per (temperature, humidity) point."""
    want = np.array([a for t, r, _, a in _rows() if t == temp_c and r == rh_pct])
    freqs = np.array([f for t, r, f, _ in _rows() if t == temp_c and r == rh_pct])
    got = atmosphere.attenuation_coefficient(freqs, temp_c, rh_pct)
    rel = np.abs(got - want) / want
    i = int(np.argmax(rel))
    assert rel.max() < TOLERANCE, (
        f"alpha({freqs[i]:.0f} Hz, {temp_c:+.0f} C, {rh_pct:.0f} % RH) = "
        f"{got[i]:.4e} dB/m, the independent reference says {want[i]:.4e} dB/m "
        f"({rel.max() * 100:.2f} % off; worst of {len(freqs)} points at this "
        f"condition)")


def test_atmosphere_reference_worst_case_is_well_inside_the_tolerance():
    """One number for the README to quote, rather than a wall of passes."""
    worst, where = 0.0, None
    for tc, rh, fq, a_ref in _rows():
        a_mine = float(atmosphere.attenuation_coefficient(fq, tc, rh))
        rel = abs(a_mine - a_ref) / a_ref
        if rel > worst:
            worst, where = rel, (tc, rh, fq)
    assert worst < TOLERANCE, f"worst deviation {worst:.3%} at {where}"
    assert worst < 0.02, f"the model has drifted: {worst:.3%} at {where}"
